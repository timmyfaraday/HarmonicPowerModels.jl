# HarmonicPowerModels.jl                                                       #
# Golden reference generator for the PCE pipeline (PolyChaos / PCEBasis).      #
#                                                                               #
# Snapshots, at full Float64 precision, the PCE-level quantities of:           #
#                                                                               #
#   A. Univariate path (network-independent; feeds hdata["pce"] and thereby   #
#      sHHC_QCQP / sHHC_SOC): M tensor, psi_norms, lambda, and per-harmonic    #
#      cos/sin PCE coefficient vectors.                                         #
#   B. Multivariate LP-reduction path, per network and harmonic: multi-index   #
#      set, per-unit cos/sin coefficient vectors, C_scalar, I_star and        #
#      binding buses for both the independent-germ and shared-germ models.     #
#                                                                               #
# History: the Phase-0 versions of the golden files were generated by the      #
# legacy native-Jacobi implementation; the rewired PolyChaos pipeline was      #
# verified against them (48/48 basis-independent quantities at rtol 1e-9,     #
# see compare_phase2_golden.jl) before the legacy code was removed. Files      #
# generated by this script use the monic Beta01 probability-measure basis;     #
# coefficient vectors are therefore NOT comparable across that boundary —      #
# only the basis-independent keys (I_star_*, binding_bus_*, C_scalar_*) are.  #
#                                                                               #
# The files were regenerated when the Taylor trig PCE was replaced by the      #
# exact quadrature projection (`affine_trig_pce`). That shifted C_scalar and   #
# I_star by 0.06 % (h=5) to 0.4 % (h=13) — the Taylor truncation error that    #
# the old golden had frozen in. Binding buses were unaffected.                 #
#                                                                               #
# Run:    julia --project test/golden/generate_pce_golden.jl                   #
# Output: test/golden/pce_golden_univariate.txt                                #
#         test/golden/pce_golden_{industrial,ieee30}.txt                       #
# Author: Tom Van Acker                                                         #

using HarmonicPowerModels, PowerModels
using Printf

include(joinpath(@__DIR__, "..", "..", "examples", "shhc", "pce_params.jl"))

const PMs = PowerModels
const HPM = HarmonicPowerModels
const OUT = @__DIR__

const HARM = [5, 7, 11, 13]

fmt(x::Real)             = @sprintf("%.17g", x)
fmt(v::AbstractVector)   = join(fmt.(v), " ")

"Write `name = scalar` or `name = v1 v2 …` line."
wln(io, name, x) = println(io, name, " = ", fmt(x))

# ── A. univariate path (building blocks of update_hdata_with_pce_data!) ──────

function write_univariate()
    α̂  = PCE_PARAMS["alpha_hat"]
    β̂  = PCE_PARAMS["beta_hat"]
    δ  = PCE_PARAMS["delta"]
    ε  = PCE_PARAMS["epsilon"]

    pb = HPM.PCEBasis(1, α̂, β̂, δ)
    M  = HPM.dense_tensor(pb)

    open(joinpath(OUT, "pce_golden_univariate.txt"), "w") do io
        println(io, "# univariate PCE golden — monic Beta01 basis " *
                    "(alpha_hat=$α̂, beta_hat=$β̂, delta=$δ, epsilon=$ε)")
        wln(io, "lambda",    HPM.cantelli_lambda(ε))
        wln(io, "psi_norms", pb.sp2)
        for k in 0:δ
            wln(io, "M[:,:,$(k)]", vec(M[:, :, k + 1]))
        end
        for h in HARM
            hb = PCE_PARAMS["harmonics"][h]
            cc, sc = HPM.affine_trig_pce(pb, 1, hb.v_min, hb.v_max)
            wln(io, "h$(h).cos_coeffs", cc)
            wln(io, "h$(h).sin_coeffs", sc)
        end
    end
    println("✓ univariate golden written")
end

# ── B. multivariate LP-reduction path ────────────────────────────────────────

function write_multivariate(tag::String, casefile::String)
    data = PMs.parse_file(joinpath(@__DIR__, "..", "..", "examples", "shhc",
                                   "data", casefile))

    α̂ = PCE_PARAMS["alpha_hat"]
    β̂ = PCE_PARAMS["beta_hat"]
    δ = PCE_PARAMS["delta"]
    ε = PCE_PARAMS["epsilon"]

    load_entries = sort([(id = parse(Int, k), bus = v["load_bus"])
                         for (k, v) in data["load"]], by = x -> x.id)
    unit_ids = [l.id for l in load_entries]
    N        = length(unit_ids)

    beta_params = (alpha_shape = α̂, beta_shape = β̂, delta = δ)

    pb = HPM.PCEBasis(N, α̂, β̂, δ)
    P  = pb.dim

    open(joinpath(OUT, "pce_golden_$(tag).txt"), "w") do io
        println(io, "# multivariate PCE golden — $tag, monic Beta01 basis " *
                    "(N=$N, delta=$δ, P=$P, epsilon=$ε)")
        println(io, "unit_ids = ", join(unit_ids, " "))
        wln(io, "norms_sq_mv", pb.sp2)
        for k in 1:P
            println(io, "multi_index[$k] = ", join(pb.ind[k, :], " "))
        end

        for h in HARM
            hb = PCE_PARAMS["harmonics"][h]
            angle_params_h = Dict(uid => (rad2deg(hb.v_min), rad2deg(hb.v_max))
                                  for uid in unit_ids)

            # end-to-end LP reduction (independent + shared germ models)
            r = HPM.compare_shared_vs_independent(data, h, ε, beta_params,
                                                  angle_params_h)
            active = HPM._active_bus_ids_lp(data, h)

            println(io, "h$(h).active_bus_ids = ", join(active, " "))
            wln(io, "h$(h).I_star_independent", r.I_star_independent)
            wln(io, "h$(h).I_star_shared",      r.I_star_shared)
            println(io, "h$(h).binding_bus_independent = ", r.binding_bus_independent)
            println(io, "h$(h).binding_bus_shared = ",      r.binding_bus_shared)
            wln(io, "h$(h).C_scalar_independent", r.C_scalar_independent)
            wln(io, "h$(h).C_scalar_shared",      r.C_scalar_shared)

            # intermediate: multivariate trig PCE of the first unit
            units = [(id = unit_ids[u],
                      h_angles = Dict(h => angle_params_h[unit_ids[u]]))
                     for u in 1:N]
            cc, sc = HPM.angle_pce_coefficients(pb, units, [h])
            wln(io, "h$(h).cos_coeffs_unit1", cc[(unit_ids[1], h)])
            wln(io, "h$(h).sin_coeffs_unit1", sc[(unit_ids[1], h)])

            @printf("  %s h=%-2d  I_ind=%.6f (bus %d)  I_sh=%.6f (bus %d)\n",
                    tag, h, r.I_star_independent, r.binding_bus_independent,
                    r.I_star_shared, r.binding_bus_shared)
        end
    end
    println("✓ $tag golden written  (N=$N, P=$P)")
end

write_univariate()
write_multivariate("industrial", "industrial_network_shhc.m")
write_multivariate("ieee30",     "30bus_network_shhc.m")
println("\nPCE golden reference complete → ", OUT)
